#!/usr/bin/env python3
"""The evening forum: storyboard/forum.txt (the script) to src/gen/forumtxt.asm
(its tables and text, in the forum's bank). See forum.txt for the format and
src/asm/forum.asm for how the tables are read.

Text is stored as ASCII (c_puts turns it into the 320A font's codes).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "storyboard" / "forum.txt"
OUT = ROOT / "src" / "gen" / "forumtxt.asm"

AVATARS = ["arthur", "pixelkid", "sue", "hal", "maria"]   # tools/gfx.py's order
SLOTS = ["opener", "bugs", "verdict"]
LIMITS = {"handle": 12, "tag": 22, "title": 38, "line": 35, "phrase": 35, "lines": 4,
          "evening": 8, "game": 30}


def fail(n, msg):
    sys.exit(f"{SRC.name}:{n}: {msg}")


def check(n, kind, text):
    if len(text) > LIMITS[kind]:
        fail(n, f"{kind} over {LIMITS[kind]} characters ({len(text)}): {text}")
    for ch in text:
        if not 32 <= ord(ch) <= 95:
            fail(n, f"{ch!r} isn't in the font (ASCII 32-95): {text}")


def main():
    users, days, posts, phrases, after = {}, [], [], [], {}
    cur_post = None
    for n, raw in enumerate(SRC.read_text().splitlines(), 1):
        line = raw.rstrip()
        if line.startswith("#") or not line.strip():
            cur_post = None if not line.strip() else cur_post
            continue
        if not line.startswith("@"):
            if cur_post is None:
                fail(n, "a text line outside a post")
            check(n, "line", line)
            cur_post["lines"].append(line)
            if len(cur_post["lines"]) > LIMITS["lines"]:
                fail(n, f"a post over {LIMITS['lines']} lines")
            continue
        head, _, text = line.partition("|")
        words, text = head.split(), text.strip()
        cmd = words[0]
        cur_post = None
        if cmd == "@user":
            key, handle, pal, av = words[1:5]
            check(n, "handle", handle)
            check(n, "tag", text)
            users[key] = dict(i=len(users), handle=handle, tag=text, pal=int(pal), av=AVATARS.index(av))
        elif cmd == "@day":
            check(n, "evening", text)
            days.append(dict(name=text, game="", threads=[]))
        elif cmd == "@game":
            check(n, "game", text)
            days[-1]["game"] = text
        elif cmd == "@thread":
            check(n, "title", text)
            days[-1]["threads"].append(dict(by=users[words[1]]["i"], release="release" in words[2:],
                                            title=text, posts=[]))
        elif cmd == "@post":
            cur_post = dict(by=users[words[1]]["i"], lines=[])
            posts.append(cur_post)
            days[-1]["threads"][-1]["posts"].append(len(posts) - 1)
        elif cmd == "@phrase":
            slot, day = SLOTS.index(words[1]), int(words[2])
            kind = "kind" in words[3:]
            last = day - 1 if "only" in words[3:] else 2
            bug = int(words[words.index("bug") + 1]) if "bug" in words else 0
            check(n, "phrase", text)
            phrases.append(dict(slot=slot, day=day - 1, last=last, kind=kind, bug=bug, text=text))
        elif cmd == "@after":
            day = int(words[1])
            kind = "kind" in words[2:]
            cur_post = dict(by=users[words[-1]]["i"], lines=[])
            posts.append(cur_post)
            after[(day - 1, kind)] = len(posts) - 1
        else:
            fail(n, f"unknown {cmd}")
    if len(days) != 3:
        sys.exit("forum.txt: three days, please")
    for d in range(3):
        rel = [t for t in days[d]["threads"] if t["release"]]
        if len(rel) != 1 or not days[d]["threads"][0]["release"]:
            sys.exit(f"forum.txt: day {d + 1}'s first thread must be its one release thread")
        if not 1 <= len(days[d]["threads"]) <= 4:
            sys.exit(f"forum.txt: day {d + 1}: 1 to 4 threads")
        after.setdefault((d, True), after[(d, False)])
    lines = [ln for p in posts for ln in p["lines"]]
    if len(lines) > 255 or len(posts) > 255 or len(phrases) > 64:
        sys.exit("forum.txt: too much text for the tables")

    out = ["; Generated by tools/forum.py from storyboard/forum.txt. Do not edit.", ""]
    strs = []

    def s(text):
        strs.append(text)
        return f"f_s{len(strs) - 1}"

    def table(name, vals):
        vals = list(vals)
        for k in range(0, max(len(vals), 1), 16):
            out.append(f"{name if k == 0 else ''} .byte " + ",".join(str(v) for v in vals[k:k + 16]))

    def ptrs(name, labels):
        table(name + "lo", [f"<{l}" for l in labels])
        table(name + "hi", [f">{l}" for l in labels])

    ulist = sorted(users.values(), key=lambda u: u["i"])
    out.append(f"F_ARTHUR = {users['arthur']['i']}")
    out.append(f"F_NPHRASES = {len(phrases)}")
    ptrs("f_un", [s(u["handle"]) for u in ulist])
    ptrs("f_ut", [s(u["tag"]) for u in ulist])
    table("f_upal", [u["pal"] for u in ulist])
    table("f_uav", [128 + 8 * u["av"] for u in ulist])
    ptrs("f_dn", [s(d["name"]) for d in days])
    ptrs("f_dg", [s(d["game"]) for d in days])
    th = [t for d in days for t in d["threads"]]
    table("f_dth0", [sum(len(days[k]["threads"]) for k in range(d)) for d in range(3)])
    table("f_dthn", [len(d["threads"]) for d in days])
    ptrs("f_tt", [s(t["title"]) for t in th])
    table("f_tby", [t["by"] for t in th])
    table("f_tp0", [t["posts"][0] for t in th])
    table("f_tpn", [len(t["posts"]) for t in th])
    table("f_trel", [1 if t["release"] else 0 for t in th])
    table("f_pby", [p["by"] for p in posts])
    l0 = []
    for p in posts:
        l0.append(sum(len(q["lines"]) for q in posts[:len(l0)]))
    table("f_pl0", l0)
    table("f_pn", [len(p["lines"]) for p in posts])
    ptrs("f_ln", [s(ln) for ln in lines])
    ptrs("f_ph", [s(p["text"]) for p in phrases])
    table("f_phslot", [p["slot"] for p in phrases])
    table("f_phday", [p["day"] for p in phrases])
    table("f_phlast", [p["last"] for p in phrases])
    table("f_phbug", [p["bug"] for p in phrases])
    table("f_phkind", [1 if p["kind"] else 0 for p in phrases])
    table("f_after", [after[(d, k)] for d in range(3) for k in (False, True)])
    for i, t in enumerate(strs):
        out.append(f"f_s{i} .byte " + ",".join(str(ord(c)) for c in t) + ",0")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    size = sum(len(t) + 1 for t in strs)
    print(f"forum: {len(th)} threads, {len(posts)} posts, {len(lines)} lines, "
          f"{len(phrases)} phrases; about {size} bytes of text")


if __name__ == "__main__":
    main()
