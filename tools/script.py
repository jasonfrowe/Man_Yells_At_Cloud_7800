#!/usr/bin/env python3
"""The story's cutscenes: storyboard/script.txt to src/gen/cuttxt.asm (bank
7, read by src/asm/cut.asm). See script.txt for the format.

A page: its speaker (an avatar, 255 none), its header (an index, 255 none),
its line count, then the lines (ASCII, zero-ended).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "storyboard" / "script.txt"
OUT = ROOT / "src" / "gen" / "cuttxt.asm"
# the speakers: tools/gfx.py's AVATARS order (the 320A font's codes 128 + 8a)
SPEAKERS = ["arthur", "pixelkid", "sue", "hal", "maria", "cloud"]


def fail(n, msg):
    sys.exit(f"{SRC.name}:{n}: {msg}")


def check(n, text, width=40):
    if len(text) > width:
        fail(n, f"over {width} characters ({len(text)}): {text}")
    for ch in text:
        if not 32 <= ord(ch) <= 95:
            fail(n, f"{ch!r} isn't in the font: {text}")


def main():
    cuts, headers = [], []
    cur = None
    hdr, spk, page = 255, 255, None

    def endpage():
        nonlocal page
        if page is not None and page["lines"]:
            cur["pages"].append(page)
        page = None

    for n, raw in enumerate(SRC.read_text().splitlines(), 1):
        line = raw.rstrip()
        if line.startswith("#"):
            continue
        if line.startswith("@cut"):
            endpage()
            w = line.split()
            if int(w[1]) != len(cuts):
                fail(n, f"number the cuts in order (next is {len(cuts)})")
            cur = dict(key=w[2], pages=[])
            cuts.append(cur)
            hdr, spk = 255, 255
        elif line.startswith("@at"):
            endpage()
            text = line[3:].strip()
            check(n, text)
            headers.append(text)
            hdr = len(headers) - 1
        elif line.startswith("= "):
            endpage()
            who = line[2:].strip()
            spk = 255 if who == "none" else SPEAKERS.index(who)
        elif not line.strip():
            endpage()
        else:
            check(n, line)
            if page is None:
                page = dict(spk=spk, hdr=hdr, lines=[])
            page["lines"].append(line)
            if len(page["lines"]) > 6:
                fail(n, "a page over 6 lines")
    endpage()

    out = ["; Generated by tools/script.py from storyboard/script.txt. Do not edit.", ""]
    pages = [p for c in cuts for p in c["pages"]]
    for i, c in enumerate(cuts):
        out.append(f"CUT_{c['key'].upper()} = {i}")
    first, k = [], 0
    for c in cuts:
        first.append(k)
        k += len(c["pages"])
    out.append("cut_first .byte " + ",".join(map(str, first)))
    out.append("cut_count .byte " + ",".join(str(len(c["pages"])) for c in cuts))
    for nm, lab in (("lo", "<"), ("hi", ">")):
        for k0 in range(0, len(pages), 16):
            out.append(f"{'cut_pg' + nm if k0 == 0 else ''} .byte " +
                       ",".join(f"{lab}cut_pg{k}" for k in range(k0, min(k0 + 16, len(pages)))))
        out.append(f"cut_hdr{nm} .byte " + ",".join(f"{lab}cut_h{k}" for k in range(len(headers))))
    for k, h in enumerate(headers):
        out.append(f'cut_h{k} .byte "{h}",0')
    for k, p in enumerate(pages):
        out.append(f"cut_pg{k} .byte {p['spk']},{p['hdr']},{len(p['lines'])}")
        for ln in p["lines"]:
            out.append(f'    .byte "{ln}",0' if ln else "    .byte 0")
    OUT.write_text("\n".join(out) + "\n")
    print(f"script: {len(cuts)} cutscenes, {len(pages)} pages")


if __name__ == "__main__":
    main()
